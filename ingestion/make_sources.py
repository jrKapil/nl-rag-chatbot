"""Deliverable D2: source list (CSV + MD) of the exactly-5 whitelisted URLs.

Regenerated by ingestion/scrape.py from data/raw/manifest.json. Both files must
always list exactly the 5 whitelisted pages (PRD D2 acceptance).
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

from config.sources import SOURCE_PAGES

DATA_RAW = Path("data/raw")
DATA = Path("data")


def _load_manifest() -> list[dict]:
    path = DATA_RAW / "manifest.json"
    if not path.exists():
        return []
    return json.loads(path.read_text(encoding="utf-8"))


def generate_source_lists() -> None:
    by_slug = {m["slug"]: m for m in _load_manifest()}

    # CSV — from the authoritative whitelist, enriched with manifest metadata
    with (DATA / "sources.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["no", "title", "url", "page_type", "fetched_at", "status"])
        for i, p in enumerate(SOURCE_PAGES, 1):
            m = by_slug.get(p.slug, {})
            w.writerow([i, p.name, p.url, p.page_type,
                        m.get("fetched_at", ""), m.get("status", "")])

    # Markdown, same content
    lines = [
        "# Source list (the 5 official public pages used)",
        "",
        "| # | Page | URL | Type | Fetched (UTC) |",
        "|---|------|-----|------|---------------|",
    ]
    for i, p in enumerate(SOURCE_PAGES, 1):
        m = by_slug.get(p.slug, {})
        lines.append(f"| {i} | {p.name} | {p.url} | {p.page_type} | {m.get('fetched_at', '')} |")
    lines += ["", "Facts-only. No investment advice.", ""]
    (DATA / "sources.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"[sources] wrote {DATA / 'sources.csv'} and {DATA / 'sources.md'}")


if __name__ == "__main__":
    generate_source_lists()
